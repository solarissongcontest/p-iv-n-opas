const stem = { version: "0.1.0", objectives: ["L1-INT-03", "L1-READ-01", "L1-MED-01"],
  difficulty: "guided" as const };
function choice(id: string, promptFi: string, labels: string[],
  correctIndex: number, explanationFi: string): Exercise {
  return { ...stem, id: "los1-c03-" + id, type: "single-choice", promptFi, explanationFi,
    options: labels.map((label, index) => ({ id: "answer-" + (index + 1), label })),
    correctOptionId: "answer-" + (correctIndex + 1) };
}
function gap(id: string, promptFi: string, before: string, after: string,
  answer: string, explanationFi: string): Exercise {
  return { ...stem, id: "los1-c03-" + id, type: "gap-fill", promptFi, explanationFi,
    sentenceBefore: before, sentenceAfter: after, acceptedAnswers: [answer] };
}
