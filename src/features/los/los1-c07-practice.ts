const base={version:"0.1.0",difficulty:"guided" as const,
  objectives:["L1-PHON-01","L1-STRAT-01"]};
const choice=(id:string,promptFi:string,options:[string,string,string],right:0|1|2,
  explanationFi:string):Exercise=>({
    ...base,id:"los1-c07-"+id,type:"single-choice",promptFi,
    options:options.map((label,i)=>({id:"o"+i,label})),
    correctOptionId:"o"+right,explanationFi,
  });
const gap=(id:string,promptFi:string,before:string,after:string,
  word:string,explanationFi:string,caseSensitive=false):Exercise=>({
    ...base,id:"los1-c07-"+id,type:"gap-fill",promptFi,
    sentenceBefore:before,sentenceAfter:after,acceptedAnswers:[word],caseSensitive,explanationFi,
  });
