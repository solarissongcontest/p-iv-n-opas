import { useState } from "react";
import { CheckCircle2, CircleAlert, RotateCcw } from "lucide-react";
import { useLosChapterDraft } from "./studyState";
import { LOS1_MIDTERM_DRAFT_CHAPTER, LOS1_MIDTERM_QUESTIONS,
  LOS1_MIDTERM_SECTION_TITLES, losExamReadyToSubmit, losExamScore } from "./content/los1Exams";
import {losArchiveExamAttempt,losArchivedExamHistory,losArchiveMidtermPersonalWork,losArchivedMidtermPersonalWork} from "./content/los1ExamArchive";
import "./los-exams.css";

const RUBRIC = [
  {id:"greeting",label:"Aloitan tervehdyksellä, joka sopii tilanteeseen."},
  {id:"name",label:"Osaan kysyä nimen ja kertoa oman kuvitteellisen nimeni."},
  {id:"origin",label:"Osaan kysyä ja kertoa lähtömaan (woher / kommen / aus)."},
  {id:"register",label:"Valitsen du- tai Sie-puhuttelun tietoisesti."},
  {id:"wellbeing",label:"Kysyn kuulumisia, vastaan ja esitän vastakysymyksen."},
] as const;

/** An individual 25-point self-study exam, with no autogenerated speaking grade.
 * Test answers and timestamps are saved in reserved draft slot 91, not a fake
 * textbook chapter. The public exam does not claim to be the school's exam.
 */
export function LosMidtermExam() {
  const {draft,update,saved}=useLosChapterDraft(1,LOS1_MIDTERM_DRAFT_CHAPTER);
  const [confirmRetake,setConfirmRetake]=useState(false);
  const [archiveError,setArchiveError]=useState("");
  const history=losArchivedExamHistory(draft.practiceAnswers,"EX-MID");
  const answers=draft.testAnswers;
  const submitted=Boolean(draft.testSubmittedAt);
  const filled=LOS1_MIDTERM_QUESTIONS.filter(q=>Boolean(answers[q.id])).length;
  const complete=losExamReadyToSubmit(LOS1_MIDTERM_QUESTIONS,answers);
  const score=submitted?losExamScore(LOS1_MIDTERM_QUESTIONS,answers):null;
  const change=(id:string,value:string)=>{
    if(submitted)return;
    update(current=>({...current,testAnswers:{...current.testAnswers,[id]:value}}));
  };
  const submit=()=>{
    if(!complete||submitted)return;
    update(current=>({...current,testSubmittedAt:new Date().toISOString()}));
  };
  const retake=()=>{
    if(!confirmRetake||!saved)return;
    try{
      update(current=>{
        const objective=losArchiveExamAttempt(
          current.practiceAnswers,"EX-MID",LOS1_MIDTERM_QUESTIONS,
          current.testAnswers,current.testSubmittedAt??"");
        const number=losArchivedExamHistory(objective,"EX-MID").at(-1)?.number;
        if (!number) throw new Error("Uusintaa ei voitu tallentaa.");
        const preserved=losArchiveMidtermPersonalWork(
          objective,number,current.applicationDraft,current.selfAssessment,
          current.practiceAnswers["EX-MID-DIALOGUE-SELF"]??"");
        // Each retake has its own ungraded personal work and rating. Earlier
        // material remains in the archive, never silently reused as new proof.
        const freshPractice={...preserved};
        delete freshPractice["EX-MID-DIALOGUE-SELF"];
        return {...current,practiceAnswers:freshPractice,
          applicationDraft:"",selfAssessment:"",
          testAnswers:{},testSubmittedAt:null};
      });
      setArchiveError("");
      setConfirmRetake(false);
    }catch(error){setArchiveError(error instanceof Error?error.message:"Koetta ei voitu arkistoida.");}
  };
  const sectionIds=Array.from(new Set(LOS1_MIDTERM_QUESTIONS.map(q=>q.section)));
  return <section className="los-inner-page los-exam" aria-label="LOS! 1:n välikoe">
    <p className="los-eyebrow">LOS! 1 / EX-MID / ITSEOPISKELUN VÄLIARVIOINTI</p>
    <h1>Välikoe · kappaleet 1–5</h1>
    <p className="los-page-intro">Tässä on 25 LOS!:n omaa, automaattisesti tarkistettavaa tehtävää. Tehtävät kattavat tervehdykset, nimet ja verbit, lähtömaan, kohteliaan puhuttelun sekä kuulumiset. Koe on itsenäisen opiskelun harjoitus, ei virallinen koulukoe.</p>
    <div className="los-exam-overview">
      <p><strong>25 pistettä</strong> · 1 piste / tehtävä · Ei aikarajaa</p>
      <p><strong>{filled}/25 vastattu</strong> · {submitted?"Palautettu":"Luonnos tallentuu vastatessasi"}</p>
      <p className={saved?"los-exam-save":"los-exam-save is-error"} role="status">{saved?
        "Tallennettu paikallisesti. Välikoe sisältyy kirjan JSON-varmuuskopioon (tallennuskohde 91).":
        "Tallennus epäonnistui. Älä sulje sivua ennen vastausten kopioimista talteen."}</p>
      {!submitted&&<p><CircleAlert size={16}/> Oikeat vastaukset ja selitykset avautuvat vasta palauttamisen jälkeen. Älä käytä sanakirjaa, jos haluat arvioida muistamistasi.</p>}
    </div>
    {sectionIds.map((section,sectionIndex)=>{
      const questions=LOS1_MIDTERM_QUESTIONS.filter(q=>q.section===section);
      return <section key={section} className="los-exam-section" aria-labelledby={"los-exam-"+section}>
        <h2 id={"los-exam-"+section}><span>{sectionIndex+1}.</span> {LOS1_MIDTERM_SECTION_TITLES[section]}</h2>
        <p>{questions.length} pistettä</p>
        <ol>
          {questions.map(q=><li key={q.id} className="los-exam-question">
            <fieldset disabled={submitted}>
              <legend><span>{Number(q.id.slice(-2))}.</span> {q.prompt}</legend>
              <div className="los-exam-answers">
                {q.choices.map(choice=><label key={choice.id} className={answers[q.id]===choice.id?"is-selected":""}>
                  <input type="radio" name={q.id} value={choice.id} checked={answers[q.id]===choice.id}
                    onChange={()=>change(q.id,choice.id)}/>
                  <span>{choice.text}</span>
                </label>)}
              </div>
            </fieldset>
            {submitted&&<div className={"los-exam-feedback "+(answers[q.id]===q.correctId?"is-correct":"is-incorrect")} role="status">
              <strong>{answers[q.id]===q.correctId?"1/1 piste":"0/1 pistettä"}.</strong>{" "}
              {q.explanation}
              {answers[q.id]!==q.correctId&&<p>Oikea vastaus: <span lang="de">{q.choices.find(c=>c.id===q.correctId)?.text}</span></p>}
            </div>}
          </li>)}
        </ol>
      </section>;
    })}
    {!submitted?<div className="los-exam-submit">
      <h2>Palauta välikoe</h2>
      <p>Varmista, että olet vastannut kaikkiin 25 kysymykseen. Palautuksen jälkeen vastauksia ei voi enää muuttaa saman yrityksen aikana, ja pisteet näytetään osioittain.</p>
      <button type="button" className="los-primary" disabled={!complete||!saved} onClick={submit}>
        <CheckCircle2 size={18}/> Palauta välikoe · {filled}/25
      </button>
      {!complete&&<p role="status">Välikokeen palautus avautuu vasta, kun kaikkiin tehtäviin on vastattu.</p>}
    </div>:<section className="los-exam-results" aria-label="Välikokeen tulokset">
      <p className="los-overline">PALAUTETTU · AUTOMAATTINEN OSIOKOE</p>
      <h2>{score?.correct} / {score?.total} pistettä</h2>
      <p>Automaattisesti tarkistettujen monivalintatehtävien tulos. Puhetta ja vapaata kirjoittamista ei ole pisteytetty tähän tulokseen.</p>
      <table><caption>Pisteet osa-alueittain</caption><thead><tr><th scope="col">Taitoalue</th><th scope="col">Oikein</th></tr></thead>
        <tbody>{score?.perSection.map(s=><tr key={s.section}><th scope="row">{s.title}</th><td>{s.correct}/{s.total}</td></tr>)}</tbody>
      </table>
      <p>Palautettu {draft.testSubmittedAt?new Date(draft.testSubmittedAt).toLocaleString("fi-FI"):""} paikalliseen opiskelutilaan.</p>
      <div className="los-exam-retake">
        <label><input type="checkbox" checked={confirmRetake} onChange={e=>setConfirmRetake(e.target.checked)}/>
          Uusi yritys säilyttää edellisen kokeen vastaukset, palautusajan ja pistetuloksen alla näkyvässä koearkistossa. Teen halutessani JSON-varmuuskopion ennen uusintaa.</label>
        <button type="button" disabled={!confirmRetake||!saved} onClick={retake}><RotateCcw size={16}/> Arkistoi tulos ja aloita uusinta</button>
      </div>
      {archiveError&&<p role="alert">{archiveError}</p>}
      <p>Uusinnassa on tällä hetkellä sama 25 kysymyksen tehtäväpankki. Vain uusi yritys ja sen pisteet erotetaan aiemmista; tehtävävarianttien vaihtelua ei vielä ole toteutettu.</p>
    </section>}
    {history.length>0&&<section className="los-exam-results" aria-label="Välikokeen aiempien yritysten arkisto">
      <h2>Aiempien yritysten arkisto</h2>
      <p>Arkisto sisältää alkuperäiset valinnat ja arvioinnin palautushetkeltä. Se sisältyy varmuuskopioon.</p>
      <ol>{history.map(item=><li key={item.number}>
        <strong>Yritys {item.number}:</strong> {item.correct}/{item.total} pistettä ·
        {" "}{new Date(item.submittedAt).toLocaleString("fi-FI")}
        <details><summary>Näytä vanhat vastaukset ja osiot</summary>
          <p>{item.choices.split("").map((choice,i)=>i+1+". "+choice).join(" · ")}</p>
          <ul>{item.sections.map(section=><li key={section.section}>
            {LOS1_MIDTERM_SECTION_TITLES[section.section as keyof typeof LOS1_MIDTERM_SECTION_TITLES]??section.section}:
            {" "}{section.correct}/{section.total}
          </li>)}</ul>
        </details>
        {(() => {
          const personal=losArchivedMidtermPersonalWork(draft.practiceAnswers,item.number);
          return personal && <details><summary>Oma keskusteluteksti ja itsearviointi</summary>
            <p className="los-exam-own-text">{personal.applicationDraft || "(Ei kirjoitettua keskustelua; mahdollisesti suullinen.)"}</p>
            <p className="los-exam-own-text">{personal.selfAssessment || "(Ei kirjoitettua itsearviointia.)"}</p>
            <p>Oma arvio: {personal.dialogueRating || "Ei valintaa"}</p>
          </details>;
        })()}
      </li>)}</ol>
    </section>}
    <section className="los-exam-speaking" aria-label="Itsenäisen viestinnän itsearviointi">
      <h2>Itsearviointi: 4–6 repliikin keskustelu</h2>
      <p>Harjoittele kuvitteellinen kohtaaminen: tervehdi, kysy nimi, kerro nimesi, kysy lähtömaa ja kuulumiset, ja vastaa sopivalla puhuttelulla. Voit esittää keskustelun ääneen tai kirjoittaa sen. Sitä ei pisteytetä automaattisesti, eikä sovellus väitä tunnistavansa ääntämistä.</p>
      <label htmlFor="los-midterm-script">Oma keskustelu tai muistiinpanot (vapaaehtoinen)</label>
      <textarea id="los-midterm-script" rows={6} maxLength={5000} value={draft.applicationDraft}
        onChange={e=>update(current=>({...current,applicationDraft:e.target.value}))}
        placeholder="Kirjoita tähän oma 4–6 repliikin kuvitteellinen keskustelusi."/>
      <label htmlFor="los-midterm-self">Mitä osasin ja mitä harjoittelen vielä?</label>
      <textarea id="los-midterm-self" rows={3} maxLength={5000} value={draft.selfAssessment}
        onChange={e=>update(current=>({...current,selfAssessment:e.target.value}))}
        placeholder="Kirjaa oma arvio rehellisesti."/>
      <fieldset className="los-exam-dialogue-self">
        <legend>Oma arvio keskustelusta (kirjataan L030-oppitunnin suoritusta varten)</legend>
        {[
          {id:"well",label:"Osasin puhua tai kirjoittaa 4–6 repliikkiä melko itsenäisesti."},
          {id:"some",label:"Sain keskustelun tehtyä, mutta tarvitsin mallia tai korjauksia."},
          {id:"again",label:"Harjoittelen keskustelua vielä uudelleen."},
        ].map(option=><label key={option.id}>
          <input type="radio" name="EX-MID-DIALOGUE-SELF" value={option.id}
            checked={draft.practiceAnswers["EX-MID-DIALOGUE-SELF"]===option.id}
            onChange={()=>update(current=>({...current,practiceAnswers:{...current.practiceAnswers,["EX-MID-DIALOGUE-SELF"]:option.id}}))}/>
          <span>{option.label}</span>
        </label>)}
      </fieldset>
      {submitted&&<div className="los-exam-rubric">
        <h3>Puheen tai kirjoituksen tarkistuslista</h3>
        <p>Tarkista itse, toteutuivatko seuraavat asiat. Niitä ei ole laskettu kokeen 25 pisteeseen.</p>
        <ul>{RUBRIC.map(item=><li key={item.id}>{item.label}</li>)}</ul>
        <p><strong>Esimerkkikeskustelu harjoittelun tueksi:</strong></p>
        <p lang="de">A: Guten Tag! Wie heißen Sie? B: Ich heiße Mia. Und Sie? A: Ich bin Leo. Woher kommen Sie? B: Ich komme aus Finnland. Wie geht es Ihnen? A: Gut, danke.</p>
        <p>Esimerkki on LOS!:n itse kirjoittama mallikeskustelu. Sitä ei väitetä alkuperäiseksi autenttiseksi lähdetekstiksi.</p>
      </div>}
    </section>
  </section>;
}
